"""Custom exception hierarchy."""
from __future__ import annotations


class DocumentBuilderError(Exception):
    """Base class; carries a user-facing message and an optional next step."""

    def __init__(self, message: str, *, hint: str = "") -> None:
        super().__init__(message)
        self.hint = hint


class SettingsValidationError(DocumentBuilderError): ...
class SettingsStorageError(DocumentBuilderError): ...
class SchemaValidationError(DocumentBuilderError): ...
class SchemaNotFoundError(DocumentBuilderError): ...
class AiResponseParseError(DocumentBuilderError): ...
class TemplateValidationError(DocumentBuilderError): ...
class TaskError(DocumentBuilderError): ...
class DependencyMissingError(DocumentBuilderError): ...
class SecretStorageUnavailableError(DocumentBuilderError): ...

# AI provider errors
class ProviderError(DocumentBuilderError): ...
class ProviderUnavailableError(ProviderError): ...
class ProviderAuthError(ProviderError): ...
class ProviderQuotaError(ProviderError): ...
class ProviderTimeoutError(ProviderError): ...
class ModelNotAvailableError(ProviderError): ...

# OCR errors (§5.3)
class OcrError(DocumentBuilderError): ...
class TesseractNotFoundError(OcrError): ...
class OcrDependencyNotInstalledError(OcrError): ...
class OcrLanguageNotSupportedError(OcrError): ...
class OcrLowConfidenceError(OcrError): ...
class OcrModelDownloadRequiredError(OcrError): ...
class PdfRenderError(OcrError): ...
class UnsupportedImageFormatError(OcrError): ...

# Export errors (§7)
class ExportError(DocumentBuilderError): ...
class UnsupportedContentError(ExportError): ...
class ExportValidationError(ExportError): ...
class OutputExistsError(ExportError): ...
class FontNotFoundError(ExportError): ...
class FormulaPolicyError(DocumentBuilderError): ...
